"""Djaq schema contract: the declarative facts Djaq needs about your data.

This is the keystone artefact. It captures ONLY declarative facts -- tables,
columns, types, choices, and the column-pairs that express relation joins --
never behaviour. It is plain data (dataclasses of primitives), so it round-trips
to JSON and may be produced from a Django model, hand-written, or generated by
an AI.

The resolver and generator depend on this contract, not on Django. A provider
(e.g. ``DjangoSchemaProvider``) is the only place coupled to a particular ORM;
once a Schema exists, the query pipeline needs no ORM at all (execution still
needs a DB connection).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field as _field
from typing import Optional

from ..exceptions import ModelNotFoundException


@dataclass(frozen=True)
class Field:
    """A concrete, selectable column on an entity."""

    name: str
    column: str
    type: str  # storage type, e.g. "DateField", "CharField" (drives date-part handling)
    choices: tuple = ()  # ((value, label), ...) -- enables ``*_display`` rewrites


@dataclass(frozen=True)
class JoinKey:
    """One equality in a join condition.

    ``left_table.left_column = right_table.right_column``. Tables are named
    explicitly so the generator can emit an ON clause without any ORM.
    """

    left_table: str
    left_column: str
    right_table: str
    right_column: str


@dataclass(frozen=True)
class Relation:
    """A traversable relationship from one entity to another.

    ``kind`` is one of ``fk``/``o2o``/``m2m``/``reverse``. For everything except
    m2m the join is a single hop (``keys``). For m2m there is an intermediate
    link table: ``link_keys`` joins the source to ``link_table`` and ``keys``
    joins ``link_table`` to the target.
    """

    name: str
    kind: str
    target: str  # key of the target entity
    keys: tuple = ()  # JoinKey... (source<->target, or link<->target for m2m)
    link_table: Optional[str] = None  # m2m only
    link_keys: tuple = ()  # m2m only: source<->link JoinKeys


@dataclass(frozen=True)
class Entity:
    """A queryable thing: a table plus its fields and relations.

    A foreign key appears in BOTH ``fields`` (its ``*_id`` column, when used as a
    terminal value) and ``relations`` (when traversed), mirroring the ORM.
    """

    key: str  # canonical identity, e.g. "books.Book"
    name: str  # short name, e.g. "Book"
    table: str
    pk: str  # primary-key column
    fields: dict = _field(default_factory=dict)  # name -> Field
    relations: dict = _field(default_factory=dict)  # name -> Relation

    def field(self, name) -> Optional[Field]:
        return self.fields.get(name)

    def relation(self, name) -> Optional[Relation]:
        return self.relations.get(name)


@dataclass
class Schema:
    """A set of entities, keyed by canonical key (e.g. ``books.Book``)."""

    entities: dict = _field(default_factory=dict)

    def get(self, name) -> Optional[Entity]:
        """Look up an entity by canonical key or short name."""
        if name in self.entities:
            return self.entities[name]
        for e in self.entities.values():
            if e.name == name:
                return e
        return None

    def get_entity(self, label) -> Entity:
        """Provider interface: return an entity or raise if it is out of scope.

        A static Schema *is* a query provider. Because resolution can only reach
        entities present here, the schema doubles as the access boundary -- a
        caller-scoped schema is a caller-scoped data surface.
        """
        entity = self.get(label)
        if entity is None:
            raise ModelNotFoundException(f"Entity not in schema: {label}")
        return entity

    def add(self, entity: Entity):
        self.entities[entity.key] = entity
        return entity

    # ---- serialisation: the contract is meant to be a portable artefact ----
    def to_dict(self) -> dict:
        return {
            "entities": {
                key: {
                    "name": e.name,
                    "table": e.table,
                    "pk": e.pk,
                    "fields": {
                        fn: {
                            "column": f.column,
                            "type": f.type,
                            "choices": [list(c) for c in f.choices],
                        }
                        for fn, f in e.fields.items()
                    },
                    "relations": {
                        rn: {
                            "kind": r.kind,
                            "target": r.target,
                            "keys": [_jk_to_dict(k) for k in r.keys],
                            "link_table": r.link_table,
                            "link_keys": [_jk_to_dict(k) for k in r.link_keys],
                        }
                        for rn, r in e.relations.items()
                    },
                }
                for key, e in self.entities.items()
            }
        }

    def to_json(self, indent=None) -> str:
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_json(cls, text: str) -> "Schema":
        return cls.from_dict(json.loads(text))

    @classmethod
    def from_dict(cls, data: dict) -> "Schema":
        schema = cls()
        for key, e in data["entities"].items():
            fields = {
                fn: Field(fn, f["column"], f["type"], tuple(tuple(c) for c in f["choices"]))
                for fn, f in e["fields"].items()
            }
            relations = {
                rn: Relation(
                    rn,
                    r["kind"],
                    r["target"],
                    tuple(_jk_from_dict(k) for k in r["keys"]),
                    r.get("link_table"),
                    tuple(_jk_from_dict(k) for k in r.get("link_keys", [])),
                )
                for rn, r in e["relations"].items()
            }
            schema.add(Entity(key, e["name"], e["table"], e["pk"], fields, relations))
        return schema


def _jk_to_dict(k: JoinKey) -> dict:
    return {
        "left_table": k.left_table,
        "left_column": k.left_column,
        "right_table": k.right_table,
        "right_column": k.right_column,
    }


def _jk_from_dict(d: dict) -> JoinKey:
    return JoinKey(d["left_table"], d["left_column"], d["right_table"], d["right_column"])
